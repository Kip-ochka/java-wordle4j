package ru.yandex.practicum;

/**
 * Состояние игры. Игровой цикл продолжается, пока состояние — {@link #IN_PROGRESS}.
 */
public enum GameState {

    /** Игра идёт: слово не отгадано и ходы ещё остались. */
    IN_PROGRESS,

    /** Слово отгадано — выигрыш. */
    WON,

    /** Ходы закончились, слово не отгадано — проигрыш. */
    LOST
}
